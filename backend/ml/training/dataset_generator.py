"""
dataset_generator.py
======================
Drives one real TraCIManager + TrafficAdapter + DigitalTwin +
FeatureEngineer run per (scenario, seed) combination, using a
DataCollector callback instead of a logging one, and writes the
resulting labeled rows to a raw per-run CSV.

This deliberately reuses the exact same runtime chain app.py already
uses. It is not a parallel feature-extraction path, it is the same
infrastructure with a different callback plugged into
TraCIManager.run(), this is what guarantees the training dataset's
features are always generated by the same FeatureEngineer logic the
runtime app uses, with no separate implementation to drift out of sync.

Requires a working SUMO installation and SUMO_HOME to be set, exactly
like app.py does, since it launches real SUMO subprocesses via
TraCIManager. This module cannot be exercised without SUMO installed.
"""

import csv
import logging
import os
from typing import List

from ml.feature_schema import (
    EXPECTED_LANE_IDS,
    LANE_FEATURE_NAMES,
    NETWORK_FEATURE_NAMES,
    PREDICTION_HORIZON_SECONDS,
    TARGET_FEATURE_NAMES,
)
from ml.training.config import TrainingConfig
from ml.training.data_collector import DataCollector
from ml.training.scenario_manifest import SCENARIOS, Scenario

logger = logging.getLogger(__name__)


class _ScenarioConfig:
    """
    A tiny, self-contained stand-in for the runtime Config class, built
    per (scenario, seed) run. TraCIManager only ever asks its config
    object for SUMOCFG_PATH and get_sumo_binary(), so this needs to
    provide exactly those two things, nothing about runtime Config is
    reused or subclassed, keeping this fully decoupled from app.py's
    configuration.
    """

    def __init__(self, sumocfg_path: str):
        self.SUMOCFG_PATH = sumocfg_path

    @staticmethod
    def get_sumo_binary() -> str:
        import sumolib

        # Headless for dataset generation, no GUI window per run, this
        # is the one deliberate difference from app.py's default of
        # "sumo-gui", dataset generation runs dozens of times unattended.
        return sumolib.checkBinary("sumo")


def _row_header() -> List[str]:
    """
    Column header for every raw CSV, matching the identity/timing +
    feature + target column layout documented in the architecture
    review's Dataset Schema section.
    """
    header = ["run_id", "scenario_name", "seed", "simulation_time", "target_time"]
    header.extend(NETWORK_FEATURE_NAMES)
    for lane_id in EXPECTED_LANE_IDS:
        for feature_name in LANE_FEATURE_NAMES:
            header.append("{}__{}".format(lane_id, feature_name))
    for lane_id in EXPECTED_LANE_IDS:
        for target_name in TARGET_FEATURE_NAMES:
            header.append("{}__target__{}".format(lane_id, target_name))
    return header


def _run_single(scenario: Scenario, seed: int) -> str:
    """
    Execute one full (scenario, seed) SUMO run and write its rows to a
    raw CSV. Returns the path written.
    """
    # Imported here rather than at module level: these modules import
    # traci, which requires SUMO_HOME to be importable at all, deferring
    # the import means the rest of this module (header generation, the
    # scenario loop) can still be imported and tested without SUMO
    # installed.
    from traffic.traci_manager import TraCIManager
    from traffic_adapter.adapter import TrafficAdapter
    from digital_twin import DigitalTwin
    from feature_engineering import FeatureEngineer

    run_id = "{}_seed{}".format(scenario.name, seed)
    sumocfg_path = os.path.join(
        TrainingConfig.SCENARIO_CONFIGS_DIR, "{}.sumocfg".format(run_id)
    )
    if not os.path.isfile(sumocfg_path):
        raise FileNotFoundError(
            "No generated sumocfg found for run '{}' at {}. Run "
            "generate_scenario_files.generate_all() first.".format(
                run_id, sumocfg_path
            )
        )

    config = _ScenarioConfig(sumocfg_path)
    manager = TraCIManager(config)
    collector = DataCollector(
        horizon_seconds=PREDICTION_HORIZON_SECONDS,
        sampling_interval_seconds=TrainingConfig.SAMPLING_INTERVAL_SECONDS,
        horizon_tolerance_seconds=TrainingConfig.HORIZON_TOLERANCE_SECONDS,
    )

    try:
        manager.start()
        adapter = TrafficAdapter(manager)
        twin = DigitalTwin()
        feature_engineer = FeatureEngineer(twin)

        def collect_step():
            state = adapter.get_current_state()
            twin.update(state)
            features = feature_engineer.generate_features()
            collector.observe(features)

        manager.run(collect_step)
    finally:
        manager.close()

    output_path = os.path.join(TrainingConfig.RAW_RUNS_DIR, "{}.csv".format(run_id))
    _write_rows_csv(output_path, run_id, scenario.name, seed, collector.rows)

    logger.info("Run '%s' complete: %d rows written to %s", run_id, len(collector.rows), output_path)
    return output_path


def _write_rows_csv(path: str, run_id: str, scenario_name: str, seed: int, rows) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(_row_header())
        for row in rows:
            writer.writerow(
                [run_id, scenario_name, seed, row.feature_time, row.target_time]
                + row.feature_vector
                + row.target_vector
            )


def generate_all() -> None:
    """
    Run every (scenario, seed) combination in the manifest and write one
    raw CSV per run. Logs progress as it goes, since a full manifest run
    can take a meaningful amount of wall-clock time.
    """
    TrainingConfig.ensure_output_directories()

    total_runs = sum(len(s.seeds) for s in SCENARIOS)
    completed = 0

    for scenario in SCENARIOS:
        for seed in scenario.seeds:
            completed += 1
            logger.info(
                "[%d/%d] Running scenario '%s' seed %d...",
                completed, total_runs, scenario.name, seed,
            )
            _run_single(scenario, seed)

    logger.info("All %d runs complete.", total_runs)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    generate_all()